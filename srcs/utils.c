#include "philo.h"

long long	ft_atol(char *s)
{
	long long	i;
	long long	ret;

	i = 0;
	ret = 0;
	if (!s)
		return (-1);
	while (s[i])
	{
		if (s[i] < '0' || s[i] > '9')
			return (-1);
		ret = (ret * 10) + (s[i] - '0');
		i++;
	}
	return (ret);
}

